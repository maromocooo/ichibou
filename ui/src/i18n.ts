const dictionaries: Record<Lang, Dict> = { en, ja, zh };

export type Key = keyof typeof en;
export type T = (key: Key, values?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = dictionaries[lang];
  return (key, values) => {
    let text = dict[key];
    for (const [name, value] of Object.entries(values ?? {})) {
      text = text.replace(`{${name}}`, String(value));
    }
    return text;
  };
}

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("aperture-lang");
    if (saved === "en" || saved === "ja" || saved === "zh") return saved;
  } catch {
    // Fall through to the browser language.
  }
  const browser = navigator.language.toLowerCase();
  if (browser.startsWith("ja")) return "ja";
  if (browser.startsWith("zh")) return "zh";
  return "en";
}

export const I18n = createContext<T>(translator("en"));
export const useT = (): T => useContext(I18n);
